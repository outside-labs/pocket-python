"""Reproduce the Unicode 16 classification used by Python string repr."""

from pathlib import Path
import sys
import platform
import unicodedata

from generate_identifiers import ranges


def generated():
    if platform.python_version() != '3.14.7' or unicodedata.unidata_version != '16.0.0':
        raise RuntimeError('Regeneration requires CPython 3.14.7 and its Unicode 16.0.0 database')
    data = ranges(lambda char: not char.isprintable())
    text = ('// Unicode 16.0.0 nonprintable ranges, generated by generate_printability.py.\n'
            '// Derived from Unicode data through pinned CPython str.isprintable().\n'
            '// Copyright and permission notice: licenses/UNICODE.txt.\n'
            'export const PRINTABILITY_UNICODE_VERSION = "16.0.0";\n'
            'const NONPRINTABLE = Object.freeze([\n')
    for index in range(0, len(data), 16):
        text += '  ' + ', '.join(hex(value) for value in data[index:index + 16]) + ',\n'
    return text + ''']);
export function isPrintable(point, charge) {
  charge(1);
  if (!Number.isInteger(point) || point < 0 || point > 0x10ffff) throw new TypeError("Invalid Unicode code point.");
  if (point < 128) return point >= 32 && point < 127;
  let low = 0, high = NONPRINTABLE.length / 2;
  while (low < high) {
    charge(1);
    const middle = Math.floor((low + high) / 2), start = NONPRINTABLE[middle * 2], end = NONPRINTABLE[middle * 2 + 1];
    if (point < start) high = middle;
    else if (point > end) low = middle + 1;
    else return false;
  }
  return true;
}
'''


if __name__ == '__main__':
    path = Path(__file__).resolve().with_name('string-printability.mjs')
    content = generated()
    if sys.argv[1:] == ['--check']:
        if path.read_text(encoding='utf-8') != content:
            raise SystemExit('Committed printability data differs from the adopted reference')
    elif not sys.argv[1:]:
        path.write_text(content, encoding='utf-8', newline='\n')
    else:
        raise SystemExit('Usage: generate_printability.py [--check]')
