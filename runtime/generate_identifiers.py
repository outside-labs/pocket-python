"""Reproduce the committed Unicode 16 Python identifier classification data."""

from pathlib import Path
import sys
import unicodedata

ROOT = Path(__file__).resolve().parent


def ranges(predicate):
    result = []
    start = None
    for point in range(0x110000):
        if predicate(chr(point)):
            if start is None:
                start = point
        elif start is not None:
            result.extend([start, point - 1])
            start = None
    if start is not None:
        result.extend([start, 0x10ffff])
    return result


def generated():
    if unicodedata.unidata_version != "16.0.0":
        raise RuntimeError("Regeneration requires the adopted Unicode 16.0.0 reference database")
    text = ('// Unicode 16.0.0 Python identifier ranges, generated by generate_identifiers.py.\n'
            '// Derived from Unicode data through CPython str.isidentifier(); no parser is used.\n'
            '// Unicode data copyright and permission notice: licenses/UNICODE.txt.\n'
            'export const IDENTIFIER_UNICODE_VERSION = "16.0.0";\n')
    for name, predicate in [("START", str.isidentifier), ("CONTINUE", lambda char: ("_" + char).isidentifier())]:
        data = ranges(predicate)
        text += "const " + name + " = Object.freeze([\n"
        for index in range(0, len(data), 16):
            text += "  " + ", ".join(hex(value) for value in data[index:index + 16]) + ",\n"
        text += "]);\n"
    return text + '''function contains(ranges, point) {
  if (!Number.isInteger(point) || point < 0 || point > 0x10ffff) return false;
  let low = 0, high = ranges.length / 2;
  while (low < high) {
    const middle = Math.floor((low + high) / 2), start = ranges[middle * 2], end = ranges[middle * 2 + 1];
    if (point < start) high = middle;
    else if (point > end) low = middle + 1;
    else return true;
  }
  return false;
}
export const isIdentifierStart = point => contains(START, point);
export const isIdentifierContinue = point => contains(CONTINUE, point);
'''


if __name__ == "__main__":
    path = ROOT / "source-identifiers.mjs"
    content = generated()
    if sys.argv[1:] == ["--check"]:
        if path.read_text(encoding="utf-8") != content:
            raise SystemExit("Committed identifier data differs from the adopted reference")
    elif not sys.argv[1:]:
        path.write_text(content, encoding="utf-8")
    else:
        raise SystemExit("Usage: generate_identifiers.py [--check]")
