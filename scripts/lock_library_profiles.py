"""Record the reviewed optional library sources without importing their code."""

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def encoded(value):
    return (json.dumps(value, indent=2, sort_keys=True) + '\n').encode()


def descriptor(path):
    data = (ROOT / 'runtime' / path).read_bytes().replace(b'\r\n', b'\n')
    return {'path': path, 'size_bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}


def catalog():
    profiles = {}
    for identity, modules in [('core-only/1', []), ('operator/1', [{
        'name': 'operator', 'package': False, 'imports': [],
        'source': descriptor('library/operator.py'), 'notice': descriptor('licenses/POCKET-PYTHON.txt')}])]:
        value = {'id': identity, 'modules': modules}
        profiles[identity] = {**value, 'fingerprint': hashlib.sha256(encoded(value)).hexdigest()}
    return profiles


def outputs():
    profiles = catalog()
    return {
        ROOT / 'runtime/library-catalog.mjs': '// Reviewed source/notice identities; generated by scripts/lock_library_profiles.py.\nexport const LIBRARY_CATALOG = ' + json.dumps(profiles, indent=2, sort_keys=True) + ';\n',
        ROOT / 'src/pocket_python/_library_lock.py': '"""Reviewed optional library identities; generated without executing library code."""\n\nLIBRARY_PROFILES = ' + repr(profiles) + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true', help='Refresh reviewed library source/notice identities.')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.write:
            path.write_text(text, encoding='utf-8', newline='\n')
        elif not path.is_file() or path.read_text(encoding='utf-8') != text:
            sys.exit('Library catalog differs; review the sources before refreshing it.')
    print('Optional library catalog verified')
